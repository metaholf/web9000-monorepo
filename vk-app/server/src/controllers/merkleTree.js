const merkleTreeController = async (req, res) => {
  if (req.body) {
    // console.log(req.body)
    const releaseId = req.body.releaseId
    const nodes = req.body.nodes
    const collection = req.body.collection
    // console.log(nodes)
    let elems = [];
    nodes.forEach((element, i) => {
      let hash = ethers.solidityPackedKeccak256(["uint256", "address", "uint256"],[releaseId, element, i]);
      elems.push(hash);
    });

    const merkleTree = new MerkleTree(elems, keccak256, { hashLeaves: false, sortPairs: true });

    const root = merkleTree.getHexRoot();

    // console.log("Root hash:", root);


    for (let i = 0; i < nodes.length; i++) {

      //
      // for user proof data
      //
      let userProofState;
      try {
        userProofState = await db.get(`proofs-${nodes[i]}`) 
        userProofState = JSON.parse(userProofState);
        // console.log("old");
      } catch (error) {
        userProofState = {};
        // console.log("new");
      }
      let data = JSON.stringify({
        collection: collection,
        releaseId: releaseId,
        leafId: i,
        proof: merkleTree.getHexProof(elems[i]),
        root: root
      });
      userProofState[keccak256(data).toString('hex')] = {
        collection: collection,
        releaseId: releaseId,
        leafId: i,
        proof: merkleTree.getHexProof(elems[i]),
        root: root
      }
      // console.log(userProofState);
      userProofState = JSON.stringify(userProofState);
      await db.put(`proofs-${nodes[i]}`, userProofState);

      //
      // for collection data
      //
      let collectionState;
      try {
        collectionState = await db.get(`collection-${collection}`) 
        collectionState = JSON.parse(collectionState);
      } catch (error) {
        collectionState = {};
      }
      collectionState[keccak256(data).toString('hex')] = {
        collection: collection,
        releaseId: releaseId,
        leafId: i,
        proof: merkleTree.getHexProof(elems[i]),
        root: root
      }
      collectionState = JSON.stringify(collectionState);
      await db.put(`collection-${collection}`, collectionState);

    }

    res.send(JSON.stringify({root: root}))

  } else
    res.send('invalid data')
}


